    help = "داده‌ی کامل و واقعی پیک آپ لند را وارد می‌کند. اجرای مکرر امن است."

    def add_arguments(self, parser):
        parser.add_argument(
            "--reset", action="store_true",
            help="محتوای قبلی (حوزه‌ها، خدمات، دوره‌ها، فراخوان‌ها و ...) را پاک و از نو می‌سازد. "
                 "پیام‌های تماس و کاربران حذف نمی‌شوند.",
        )

    @transaction.atomic
    def handle(self, *args, **options):
        if options["reset"]:
            for model in RESET_MODELS:
                model.objects.all().delete()
            self.stdout.write(self.style.WARNING("محتوای قبلی پاک شد."))

        self._fields()
        self._services()
        self._steps()
        self._courses()
        self._jobs()
        self._announcements()
        self._stats()

        self.stdout.write(self.style.SUCCESS("داده‌ی کامل پیک آپ لند ثبت شد:"))
        self.stdout.write(
            f"  حوزه‌ها: {TechField.objects.count()} | خدمات: {Service.objects.count()} | "
            f"مراحل عضویت: {ProcessStep.objects.count()}\n"
            f"  دوره‌ها: {Course.objects.count()} | ارکان دوره: {CoursePillar.objects.count()} | "
            f"موقعیت‌های شغلی: {JobOpening.objects.count()}\n"
            f"  فراخوان‌ها: {Announcement.objects.count()} | اعداد نمایشی: {Stat.objects.count()}"
        )
        self.stdout.write("هزینه‌ها، تاریخ‌ها و متن‌ها را در صورت تغییر، از پنل مدیریت ویرایش کنید.")

    def _fields(self):
        for i, (code, title, description, icon) in enumerate(FIELDS):
            TechField.objects.update_or_create(
                code=code,
                defaults={"title": title, "description": description, "icon": icon, "order": i},
            )

    def _services(self):
        for i, (title, description, points, icon) in enumerate(SERVICES):
            Service.objects.update_or_create(
                title=title,
                defaults={"description": description, "points": points, "icon": icon,
                          "order": i, "is_active": True},
            )

    def _steps(self):
        for i, (title, description) in enumerate(STEPS):
            ProcessStep.objects.update_or_create(
                title=title, defaults={"description": description, "order": i}
            )

    def _courses(self):
        for data in COURSES:
            fields = {k: v for k, v in data.items() if k != "pillars"}  # کپی؛ داده‌ی سراسری تغییر نمی‌کند
            course, _ = Course.objects.update_or_create(
                code=fields["code"],
                defaults={**fields, "is_active": True},
            )
            course.pillars.all().delete()
            for i, (title, description) in enumerate(data["pillars"]):
                CoursePillar.objects.create(course=course, title=title, description=description, order=i)

    def _jobs(self):
        for i, (title, track, description) in enumerate(JOBS):
            JobOpening.objects.update_or_create(
                title=title,
                defaults={"track": track, "description": description,
                          "requirements": JOB_REQUIREMENTS, "is_open": True, "order": i},
            )

    def _announcements(self):
        for item in ANNOUNCEMENTS:
            Announcement.objects.update_or_create(
                slug=item["slug"],
                defaults={
                    "title": item["title"],
                    "summary": item["summary"],
                    "body": item["body"],
                    "published_at": timezone.make_aware(item["published_at"]),
                    "is_published": True,
                },
            )

    def _stats(self):
        for i, (label, value) in enumerate(STATS):
            Stat.objects.update_or_create(label=label, defaults={"value": value, "order": i})
